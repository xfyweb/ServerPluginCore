const hex = (b) => Buffer.from(b).toString('hex');
const sig = (fn) => {
  try {
    const v = fn();
    if (v instanceof Uint8Array) return 'OK bytes:' + hex(v);
    return 'OK ' + JSON.stringify(v === undefined ? '<undefined>' : v, (k, x) => (typeof x === 'bigint' ? x.toString() + 'n' : x));
  } catch (e) {
    return 'THROW ' + e.name + ':' + e.code + ' | ' + e.message;
  }
};
const p = (label, fn) => console.log(label.padEnd(46) + ' => ' + sig(fn));

